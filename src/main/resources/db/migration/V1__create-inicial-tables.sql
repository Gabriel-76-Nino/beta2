CREATE TABLE ordens_servicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pessoa_id BIGINT NOT NULL,
    data_entrada TIMESTAMP NOT NULL,
    aparelho_cliente VARCHAR(255) NOT NULL,
    problema_relatado VARCHAR(1000) NOT NULL,
    acessorios_cliente VARCHAR(255),
    atendente_recebeu VARCHAR(255) NOT NULL,
    tecnico_responsavel VARCHAR(255),
    diagnostico_tecnico VARCHAR(1000),
    diagnostico_igual_relato BOOLEAN,
    statusos VARCHAR(30) NOT NULL,
    testes_realizados VARCHAR(255),
    cpf_retirante VARCHAR(20),
    nome_retirante VARCHAR(255),

    CONSTRAINT fk_os_id_pessoas
        FOREIGN KEY (pessoa_id)
        REFERENCES pessoas(id)
);

CREATE TABLE orcamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id BIGINT NOT NULL,
    numero_item INTEGER NOT NULL,
    id_produto BIGINT,
    descricao VARCHAR(255),
    quantidade INTEGER,
    preco_peca NUMERIC(12,4),
    preco_mao_obra NUMERIC(12,4),
    status_item_orcamento VARCHAR(30) NOT NULL,
    observacoes VARCHAR(1000),

    CONSTRAINT fk_orcamento_id_os
        FOREIGN KEY (ordem_servico_id)
            REFERENCES ordens_servicos(id),

    CONSTRAINT uk_orcamento_item
        UNIQUE (ordem_servico_id, numero_item)
);

