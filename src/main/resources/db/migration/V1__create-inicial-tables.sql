
create table marcas(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_marca varchar(100) not null
);

create table departamentos(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_departamento varchar(40) not null
);

create table categorias(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_categoria varchar(40) not null,
    id_departamento bigint,

    CONSTRAINT fk_categoria_departamento
        FOREIGN KEY (id_departamento)
        REFERENCES departamentos(id)
);

create table subcategorias(
    id bigint generated by default as identity primary key,
    nome_subcategoria varchar(40) not null,
    id_departamento bigint,
    id_categoria bigint,

    CONSTRAINT fk_subcategoria_departamento
        FOREIGN KEY (id_departamento)
        REFERENCES departamentos(id),

    CONSTRAINT fk_subcategoria_categoria
        FOREIGN KEY (id_categoria)
        REFERENCES categorias(id)
);

create table pessoas(
    id bigint generated by default as identity primary key,
    nome varchar(1000) not null,
    razao_social varchar(1000) not null,
    cpf_cnpj varchar(14) not null,
    email varchar(255) not null,
    nacimento_funcacao date not null,
    telefone_titular varchar(14) not null,
    nome_segunda_pessoa varchar(1000),
    telefone_segunda_pessoa varchar(14),
    cliente boolean,
    funcionario boolean,
    fornecedor boolean,
    site_fornecedor varchar(1000),
    logradouro varchar(255) not null,
    numero varchar(10),
    bairro varchar(255) not null,
    complemento varchar(255),
    cidade varchar(255) not null,
    uf varchar(2) not null,
    cep varchar(8) not null
);

create table garantias(
    id bigint generated by default as identity primary key,
    id_fornecedor bigint,
    detalhes_garantia varchar(500),
    tempo_garantia integer,

    constraint fk_garantia_fornecedor
        foreign key (id_fornecedor)
        references pessoas(id)
);

create table unidades_medidas(
    id bigint generated by default as identity primary key,
    codigo varchar(3) not null,
    descricao varchar(40) not null,
    multiplicador integer
);

CREATE TABLE produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(40) NOT NULL,
    descricao_comercial VARCHAR(255) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    id_marca BIGINT NOT NULL,
    id_departamento BIGINT NOT NULL,
    id_categoria BIGINT NOT NULL,
    id_subcategoria BIGINT NOT NULL,
    id_fornecedor BIGINT NOT NULL,
    margem DOUBLE PRECISION,
    custo_medio NUMERIC(12,4),
    preco_venda NUMERIC(12,4),
    preco_sugestao NUMERIC(12,4),
    minimo INTEGER,
    maximo INTEGER,
    id_garantia BIGINT,
    id_unidade_medida BIGINT,
    ativo BOOLEAN,
    foto VARCHAR(1000),


    CONSTRAINT fk_produto_marca
        FOREIGN KEY (id_marca)
        REFERENCES marcas(id),

    CONSTRAINT fk_produto_departamento
        FOREIGN KEY (id_departamento)
        REFERENCES departamentos(id),

    CONSTRAINT fk_produto_categoria
        FOREIGN KEY (id_categoria)
        REFERENCES categorias(id),

    CONSTRAINT fk_produto_subcategoria
        FOREIGN KEY (id_subcategoria)
        REFERENCES subcategorias(id),

    CONSTRAINT fk_produto_fornecedor
        FOREIGN KEY (id_fornecedor)
        REFERENCES pessoas(id),

    CONSTRAINT fk_produto_garantia
        FOREIGN KEY (id_garantia)
        REFERENCES garantias(id),

    CONSTRAINT fk_produto_unidade_medida
        FOREIGN KEY (id_unidade_medida)
        REFERENCES unidades_medidas(id)

);

create table estoques(
    id bigint generated by default as identity primary key,
    id_produto bigint,
    estoque_contabil integer,
    saldo_ordem_servico integer,
    saldo_pedido_venda integer,
    saldo_trocas integer,

    constraint fk_estoque_produto
        foreign key (id_produto)
        references produtos(id)
);

create table compatibilidade(
    id bigint generated by default as identity primary key,
    id_produto bigint not null,
    compativel varchar(255) not null,

    constraint fk_compatibilidade_produto
        foreign key (id_produto)
            references produtos(id)
);

create table usuarios(
    id bigint generated by default as identity primary key,
    nome_usuario varchar(255) not null unique,
    id_pessoa bigint not null,
    funcao varchar(255) not null,
    ativo boolean,

    constraint fk_usuario_pessoa
        foreign key (id_pessoa)
